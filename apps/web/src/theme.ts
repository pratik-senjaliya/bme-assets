import { theme, type ThemeConfig } from 'antd';

// Design tokens in one place. Warm stone surfaces, a deep-teal frame and one teal accent; dark mode ("night shift")
// uses the same roles with darker values. Hairline borders, small radii (4 tags, 6 controls, 8 cards), no shadows on
// resting surfaces: only what floats (menus, dialogs) gets one.
//
// PALETTE holds the real values for each mode. globals.css carries the same values as CSS variables, and COLORS
// points at those variables, so inline styles follow the mode without re-rendering. Ant Design needs real colours to
// derive hover and active shades, so its tokens are built from PALETTE.
